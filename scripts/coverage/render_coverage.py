"""Render COVERAGE.md from bindmap.json.

python3 scripts/coverage/render_coverage.py bindmap.json <core rev> COVERAGE.md
"""

import collections
import json
import sys

d = json.load(open(sys.argv[1]))
rev = sys.argv[2]
out = sys.argv[3]

GENERIC = {
    "new",
    "default",
    "len",
    "is_empty",
    "get",
    "iter",
    "clone",
    "from",
    "into",
    "as_str",
    "to_string",
    "value",
    "values",
    "name",
    "kind",
    "parse",
    "encode",
}

rows_by_mod = collections.OrderedDict()
counts = collections.Counter()
method_counts = collections.Counter()
for it in sorted(
    d, key=lambda x: (x["crate"] != "sidereon_core", x["defined_in"], x["name"])
):
    mod = it["defined_in"]
    rows = rows_by_mod.setdefault(mod, [])
    syms = it["symbols"]
    if syms:
        status = "exposed"
    else:
        status = "MISSING"
    counts[status] += 1
    path = it["paths"][0]
    feature = ""
    if it["cfg"]:
        feature = " (" + "; ".join(it["cfg"]) + ")"
    sym_text = ", ".join(f"`{s}`" for s in syms[:4]) + (
        f" and {len(syms) - 4} more" if len(syms) > 4 else ""
    )
    rows.append((f"`{path}`{feature}", it["kind"], sym_text or "-", status))
    if it["kind"] in ("struct", "enum", "trait", "union", "type"):
        for m in it["methods"]:
            callers = it["method_calls"].get(m, [])
            if syms and callers:
                mstatus = "exposed"
            else:
                mstatus = "MISSING"
            method_counts[mstatus] += 1
            ctext = ", ".join(f"`{c}`" for c in callers[:3]) or "-"
            rows.append((f"`{it['name']}::{m}`", "method", ctext, mstatus))

lines = []
lines.append("# Python binding coverage of the sidereon public API")
lines.append("")
lines.append(f"Core revision: `{rev}`.")
lines.append("")
INTRO = (
    "Every item the `sidereon-core` and `sidereon` crates make reachable through "
    "a public path, with the Python symbol that exposes it, or `MISSING`. The "
    "list is generated by `scripts/coverage/` from the core source and this "
    "package's `src/`. `pubapi.py` walks each crate's module tree from `lib.rs` "
    "(public modules, `pub use` re-exports and globs, items outside "
    "`#[cfg(test)]`) and lists each item once under its shortest public path, "
    "with the inherent `pub fn` methods of each type. `bindmap.py` marks an item "
    "exposed where a `#[pyclass]` holds it or a `#[pyfunction]` or `#[pymethods]` "
    "body (directly or through a helper it calls) refers to it, and a method "
    "exposed where such a body calls it by name. The method match is by name, so "
    "a method that shares its name with another type's can read as exposed when "
    "only the other is."
)
lines.append(INTRO)
lines.append("")
lines.append("## Counts")
lines.append("")
lines.append("| | exposed | MISSING |")
lines.append("|---|---|---|")
lines.append(f"| items | {counts['exposed']} | {counts['MISSING']} |")
lines.append(
    f"| methods of items | {method_counts['exposed']} | {method_counts['MISSING']} |"
)
lines.append("")
lines.append("## Items by defining module")
lines.append("")
for mod, rows in rows_by_mod.items():
    ex = sum(1 for r in rows if r[3] == "exposed")
    lines.append(f"### `{mod}` ({ex} of {len(rows)} exposed)")
    lines.append("")
    lines.append("| Core item | Kind | Python symbol | Status |")
    lines.append("|---|---|---|---|")
    for r in rows:
        lines.append(f"| {r[0]} | {r[1]} | {r[2]} | {r[3]} |")
    lines.append("")
open(out, "w").write("\n".join(lines))
print(counts, method_counts)
